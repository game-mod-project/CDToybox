#pragma once

// 담금질·연마 칸의 입력값 상태.
//
// 칸은 두 가지를 동시에 해야 한다: (1) 사용자가 타이핑하는 동안 그 값을 들고 있고,
// (2) **게임 값이 바뀌면** 그 값을 보여야 한다. 예전에는 (1)만 했다 - 인스턴스별로 한 번
// 씨앗을 넣고 그 뒤로는 절대 안 덮었다. 그래서 "전부 연마 최대" 로 메모리가 40 이 돼도
// 칸은 옛 숫자 2 를 영영 들고 있었고(사용자 화면 2026-09-23, 탐침으로 메모리 40 확인),
// 쓰기가 안 먹은 것처럼 보였다. 내구도가 닳아 게임이 값을 낮춰도 마찬가지였다.
//
// 그래서 마지막으로 본 게임 값(seen)을 같이 들고 다닌다. 게임 값이 달라진 프레임에만
// 다시 씨앗을 넣으므로, 타이핑 중에는(게임 값이 그대로면) 입력이 살아 있다.

namespace cdtb::render {

struct LevelEdit {
    int v = 0;      // 칸에 들어 있는 값(사용자가 고칠 수 있다)
    int seen = -1;  // 마지막으로 본 게임 값. u16 이라 -1 은 "아직 못 봤다" 다.
};

// 게임 값 cur 을 반영한다. 달라졌으면 입력값을 그 값으로 되돌린다.
inline void level_edit_sync(LevelEdit* e, int cur) {
    if (e == nullptr || e->seen == cur) return;
    e->v = cur;
    e->seen = cur;
}

}  // namespace cdtb::render
